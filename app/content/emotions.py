"""Контент по эмоциям: оттенки, значение, техники самопомощи"""

from __future__ import annotations

from dataclasses import dataclass

# Блоки «как себе помочь». Порядок задаёт порядок кнопок.
HELP_BLOCK_TITLES: dict[str, str] = {
    "acceptance": "Признание",
    "cognitive": "Когнитивный подход",
    "breathing": "Через дыхание",
    "body": "Через тело",
    "restraint": "Чтобы не сорваться",
}
HELP_BLOCK_ORDER: tuple[str, ...] = tuple(HELP_BLOCK_TITLES)


@dataclass(frozen=True)
class Emotion:
    key: str
    title: str
    meaning: str
    help: dict[str, str]
    shades: tuple[str, ...] = ()
    # Творительный падеж с предлогом — для кнопки «Помочь со злостью».
    instrumental: str = ""

    def help_blocks(self) -> tuple[str, ...]:
        """Только те блоки, для которых есть текст."""
        return tuple(block for block in HELP_BLOCK_ORDER if self.help.get(block))


