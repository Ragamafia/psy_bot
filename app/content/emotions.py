# Блоки «как себе помочь». Порядок задаёт порядок кнопок.
HELP_BLOCK_TITLES: dict[str, str] = {
    "acceptance": "Признание эмоции",
    "cognitive": "Когнитивный подход",
    "breathing": "Через дыхание",
    "body": "Через тело",
    "restraint": "Чтобы не сорваться",
}
HELP_BLOCK_ORDER: tuple[str, ...] = tuple(HELP_BLOCK_TITLES)


@dataclass(frozen=True)
class Shade:
    title: str
    # Пояснение показывается на экране значения, а не на кнопке: у зависти
    # оттенки без расшифровки непонятны, у остальных эмоций говорят сами за себя.
    note: str = ""


def _shades(*items: str | tuple[str, str]) -> tuple[Shade, ...]:
    return tuple(Shade(item) if isinstance(item, str) else Shade(*item) for item in items)


@dataclass(frozen=True)
class Emotion:
    key: str
    title: str
    meaning: str
    help: dict[str, str]
    shades: tuple[Shade, ...] = ()
    # Творительный падеж с предлогом — для кнопки «Помочь со злостью».
    instrumental: str = ""

    def help_blocks(self) -> tuple[str, ...]:
        """Только те блоки, для которых есть текст."""
        return tuple(block for block in HELP_BLOCK_ORDER if self.help.get(block))


